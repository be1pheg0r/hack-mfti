shouldSplitInstructionPrompt = """
Ты анализируешь объявления об услугах ремонта.
Твоя задача: определить, предлагает ли исполнитель хотя бы одну услугу из списка КАК САМОСТОЯТЕЛЬНУЮ, отдельно от ремонта под ключ.

Микрокатегории:
102: Сантехника — трубы, унитазы, смесители, водоснабжение
103: Электрика — проводка, розетки, щитки, светильники
104: Натяжные потолки
105: Укладка плитки — кафель, керамогранит, мозаика
106: Поклейка обоев
107: Малярные работы — покраска стен, потолков
108: Штукатурные работы — штукатурка, шпаклёвка
109: Напольные покрытия — ламинат, линолеум, паркет
110: Гипсокартон
111: Демонтажные работы

Ключевое правило:
- если автор в одном объявлении перечисляет услуги списком (буллетами, нумерацией, строками) и/или пишет, что делает их "отдельно" или "по отдельности", это само по себе НЕ повод для split.
- в таком случае ставь False.

Примеры, где обязательно shouldSplit=False:
1) "выполняю ремонтные и отделочные работы от эконом класса до люкс: ...\n- шпатлевка и штукатурка стен;\n- демонтаж стен и перегородок;\n- укладка кафельной плитки и напольных покрытий;\n- установка сантехники; ..."
   Причина: автор просто перечисляет, что делает в рамках одного объявления.
2) "Стрoительствo и Ремонт ... НАШИ УСЛУГИ👇 ... ✅ ... ✅ ..."
   Причина: длинный список услуг и преимущества бригады, но это единое объявление-описание, не сигнал к split.
3) "укладка плитки в доме квартире быстро качественно и не дорого"
   Причина: в запросе только одна микрокатегория (укладка плитки), shouldSplit=False.

True если:
- ставь shouldSplit=True ТОЛЬКО если мастер явно подает услугу как отдельную (отдельный заказ/отдельная услуга/самостоятельный оффер), а не как единый комплекс "все вместе".
- если это узкоспециализированное объявление по одной микрокатегории с собственным оффером/ценой (например только натяжные потолки), это тоже shouldSplit=True.
- даже без слов-маркеров ("отдельно", "по отдельности") ставь shouldSplit=True, если в тексте явно перечислены самостоятельные услуги из разных микрокатегорий (например плитка + сантехника + электрика как отдельные виды работ).

Пример, где обязательно shouldSplit=True:
- "Устанавливаем натяжные потолки любой сложности ... Цена за кв.м."
  Причина: самостоятельная отдельная услуга (одна микрокатегория), поданная как отдельный оффер.
- "Предлагаем профессиональную услугу по малярным работам ... Шпатлевка стен под обои/покраску, окраска стен, оклейка обоями"
  Причина: отдельный специализированный оффер по малярным работам с узким набором близких операций.
- "Качественные ремонты ванных комнат и сан.узлов под ключ ... плитка (керамогранит, мозаика), установка смесителей/раковин/унитазов/душевых, водоснабжение, канализация, услуги электрика"
  Причина: перечислены самостоятельные услуги из разных микрокатегорий (105 + 102 + 103), значит shouldSplit=True даже без явных слов-маркеров.

False если:
- услуги перечислены как состав одного предложения (включая буллеты, нумерацию, "отдельно", "по отдельности");
- нет явного сигнала про необходимость выделять отдельные черновики;
- перечисление используется только для детализации того, что делает исполнитель, или как комплекс "все вместе".

Похожие объявления с ответами помогут тебе откалиброваться.
Верни строго JSON-объект без пояснений:
{"shouldSplit": true/false, "multiCats": true/false}

Правила для multiCats:
- True, если явно присутствуют несколько самостоятельных тематик (например сантехника + электрика + плитка).
- False, если доминирует одна тема или нет явных признаков нескольких категорий.
"""


